import { chromium } from '../core-ui/node_modules/playwright/index.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const url = process.argv[2] || 'http://localhost:19731';
if (!/^http:\/\/localhost:\d+$/.test(url)) throw new Error('Loopback fixture only');
const output = process.env.DASHBOARD_REPORTS || 'reports/dashboard-browser';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({headless: true});
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  let removingPath = null, removingAt = Infinity;
  page.on('pageerror', e => errors.push({type:'page', message:e.message}));
  page.on('response', async r => { if(r.status() >= 400 && r.url().startsWith(url)) errors.push({status:r.status(), url:r.url(), observedAt:Date.now(), body:await r.text().catch(()=> '')}); });
  await page.goto(url);
  await page.getByLabel('Email').fill('sdk@example.invalid');
  await page.getByLabel('Password', {exact:true}).fill('loopback-test-only');
  const listing = page.waitForResponse(r => new URL(r.url()).pathname === '/api/blue/v1/documents' && r.status() === 200);
  await page.getByRole('button', {name: 'Sign in', exact: true}).click();
  await (await listing).finished();
  await page.getByRole('heading', {name:'Documents', exact:true}).waitFor({timeout:15000});
  await page.locator('.loading').waitFor({state:'hidden'});
  await page.screenshot({path:output+'/documents.png', fullPage:true});
  await writeFile(output+'/documents.txt', await page.locator('body').innerText());
  for (const route of ['timelines','packages','api-keys','settings']) {
    await page.goto(url+'/#'+route);
    await page.waitForTimeout(700);
    await page.screenshot({path:output+'/'+route+'.png',fullPage:true});
    await writeFile(output+'/'+route+'.txt', await page.locator('body').innerText());
  }
  await page.goto(url+'/#documents');
  await page.getByRole('button', {name:'Bootstrap document',exact:true}).click();
  const payload = page.getByLabel('Bootstrap payload');
  await payload.waitFor();
  await page.waitForFunction(() => document.querySelector('textarea')?.value.includes('REPLACE_BOB_ACCOUNT_ID'));
  let text = await payload.inputValue();
  const owner = text.match(/accountId: (user-[a-z0-9]+)/)[1];
  await payload.fill(text.replace('REPLACE_BOB_ACCOUNT_ID', owner));
  await page.getByRole('button', {name:'Bootstrap',exact:true}).click();
  await page.getByRole('tab', {name:'Operations',exact:true}).waitFor({timeout:15000});
  await page.screenshot({path:output+'/counter.png',fullPage:true});
  await page.getByRole('button', {name:'Pause processing',exact:true}).click();
  await page.getByRole('button', {name:'Resume processing',exact:true}).filter({has:page.locator('svg')}).waitFor();
  await page.screenshot({path:output+'/paused.png',fullPage:true});
  await page.getByRole('button', {name:'Resume processing',exact:true}).filter({has:page.locator('svg')}).click();
  await page.getByRole('button', {name:'Pause processing',exact:true}).waitFor();
  await page.getByRole('tab', {name:'Links',exact:true}).click();
  await page.waitForTimeout(300);
  await page.screenshot({path:output+'/links.png',fullPage:true});
  await page.getByRole('tab', {name:'Operations',exact:true}).click();
  await page.getByRole('button', {name:'Invoke operation',exact:true}).first().click();
  await page.getByText(/Processed. Review the document/).waitFor({timeout:15000});
  await page.screenshot({path:output+'/operation.png',fullPage:true});
  await page.getByRole('tab', {name:'History',exact:true}).click();
  await page.waitForTimeout(500);
  await page.screenshot({path:output+'/history.png',fullPage:true});
  await writeFile(output+'/history.txt', await page.locator('body').innerText());
  const documentUrl = page.url();
  await page.goto(url+'/#events');
  await page.getByRole('heading',{name:'MyOS Events',exact:true}).waitFor();
  await page.locator('.filter-panel select').selectOption('DOCUMENT_EPOCH_ADVANCED');
  await page.getByRole('link',{name:'DOCUMENT_EPOCH_ADVANCED',exact:true}).first().waitFor();
  assert.equal(await page.getByRole('alert').count(),0);
  await page.screenshot({path:output+'/events.png',fullPage:true});
  await page.getByRole('link',{name:'DOCUMENT_EPOCH_ADVANCED',exact:true}).first().click();
  await page.getByRole('heading',{name:'Event details',exact:true}).waitFor();
  await page.getByText('Committed event · DOCUMENT_EPOCH_ADVANCED',{exact:true}).waitFor();
  await page.screenshot({path:output+'/event-detail.png',fullPage:true});
  await writeFile(output+'/event-detail.txt',await page.locator('body').innerText());

  const personalWorkspace = await page.getByLabel('Workspace', {exact:true}).inputValue();
  await page.goto(url+'/#settings/accounts');
  await page.getByRole('button', {name:'Create account',exact:true}).click();
  const creation = page.getByRole('dialog', {name:'Create account',exact:true});
  await creation.getByLabel('Business Name').fill('Browser workspace');
  await creation.getByRole('button', {name:'Create account',exact:true}).click();
  await creation.waitFor({state:'hidden'});
  await page.waitForFunction(() => document.querySelector('select[aria-label="Workspace"]')?.selectedOptions[0]?.textContent.includes('Browser workspace'));
  await page.screenshot({path:output+'/workspace.png',fullPage:true});
  await page.goto(url+'/#settings/users');
  await page.getByRole('cell', {name:'sdk@example.invalid (you)', exact:true}).waitFor();
  assert.equal(await page.getByRole('alert').count(),0);
  await page.screenshot({path:output+'/workspace-users.png',fullPage:true});
  await writeFile(output+'/workspace-users.txt',await page.locator('body').innerText());

  const imageData = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = canvas.height = 32; const context = canvas.getContext('2d'); context.fillStyle = '#427beb'; context.fillRect(0, 0, 32, 32); return canvas.toDataURL('image/png').split(',')[1]; });
  const imageFile = {name:'fixture.png', mimeType:'image/png', buffer:Buffer.from(imageData, 'base64')};
  await page.goto(url+'/#settings/accounts');
  await page.getByLabel('Choose account image', {exact:true}).setInputFiles(imageFile);
  await page.getByRole('button', {name:'Save account image',exact:true}).click();
  await page.getByRole('button', {name:'Remove account image',exact:true}).waitFor();
  await page.waitForFunction(() => { const image = document.querySelector('img[alt="Account logo"]'); return image?.complete && image.naturalWidth > 0; });
  await page.screenshot({path:output+'/workspace-logo.png',fullPage:true});
  await page.getByRole('button', {name:'Remove account image',exact:true}).click();
  await page.getByRole('button', {name:'Remove account image',exact:true}).waitFor({state:'hidden'});
  await page.goto(url+'/#settings/profile');
  await page.getByLabel('Add an avatar', {exact:true}).setInputFiles(imageFile);
  await page.getByRole('button', {name:'Save avatar',exact:true}).click();
  await page.getByRole('button', {name:'Remove avatar',exact:true}).waitFor();
  await page.waitForFunction(() => { const image = document.querySelector('img[alt="Your avatar"]'); return image?.complete && image.naturalWidth > 0; });
  await page.screenshot({path:output+'/user-avatar.png',fullPage:true});
  await page.getByRole('button', {name:'Remove avatar',exact:true}).click();
  await page.getByRole('button', {name:'Remove avatar',exact:true}).waitFor({state:'hidden'});
  await page.goto(url+'/#documents');
  await page.locator('.loading').waitFor({state:'hidden'});
  await page.locator('.data-table .empty-cell').waitFor();
  assert.equal(await page.locator('.data-table tbody tr.cursor-pointer').count(), 0, 'New workspace has no personal documents');
  const restored = page.waitForResponse(r => new URL(r.url()).pathname === '/api/blue/v1/account' && r.status() === 200 && r.request().headers()['x-myos-account'] === personalWorkspace);
  await page.getByLabel('Workspace', {exact:true}).selectOption(personalWorkspace);
  assert.equal((await (await restored).json()).accountId, personalWorkspace);
  await page.getByRole('heading', {name:'Documents',exact:true}).waitFor();
  await page.locator('.loading').waitFor({state:'hidden'});
  await page.goto(documentUrl);
  await page.getByRole('tab', {name:'History',exact:true}).waitFor();
  const removedSession = new URL(page.url()).hash.slice('#documents/'.length).split('?')[0];
  const retained = await (await page.request.get(url+'/api/blue/v1/documents/'+removedSession, {headers:{'X-MyOS-Account':personalWorkspace}})).json();
  await page.getByRole('button', {name:'Delete document',exact:true}).click();
  const deletion = page.getByRole('dialog', {name:'Delete document',exact:true});
  removingPath = '/api/blue/v1/documents/'+removedSession; removingAt = Date.now();
  await deletion.getByRole('button', {name:'Delete',exact:true}).click();
  await page.getByRole('heading', {name:'Documents',exact:true}).waitFor();
  await page.locator('.loading').waitFor({state:'hidden'});
  await page.screenshot({path:output+'/unlinked.png',fullPage:true});
  await page.getByRole('button', {name:'Add new',exact:true}).click();
  await page.getByLabel('Input mode').selectOption('reference');
  await page.getByLabel('YAML or JSON').fill(retained.lastStable.documentRef.blueId);
  await page.getByRole('button', {name:'Start document',exact:true}).click();
  await page.getByRole('tab', {name:'History',exact:true}).waitFor();
  const replacementSession = new URL(page.url()).hash.slice('#documents/'.length).split('?')[0];
  assert.notEqual(replacementSession,removedSession);
  const reattached = await (await page.request.get(url+'/api/blue/v1/documents/'+replacementSession, {headers:{'X-MyOS-Account':personalWorkspace}})).json();
  assert.equal(reattached.instanceId,retained.instanceId);
  assert.deepEqual(reattached.lastStable,retained.lastStable);
  await page.getByRole('tab', {name:'History',exact:true}).click();
  await page.locator('.loading').waitFor({state:'hidden'});
  await page.screenshot({path:output+'/reattached-history.png',fullPage:true});
  await writeFile(output+'/errors.json', JSON.stringify(errors,null,2));
  const unexpected = errors.filter(e => !(e.status === 401 && e.url.endsWith('/api/blue/v1/me'))
    && !(e.status === 404 && new URL(e.url).pathname === removingPath && e.observedAt >= removingAt));
  assert.deepEqual(unexpected, [], 'Signed-in dashboard must have no browser or HTTP errors');
  assert.doesNotMatch(await page.locator('body').innerText(), /Waiting \[\]/);
  console.log(JSON.stringify({screens:18, errors},null,2));
} finally { await browser.close(); }
